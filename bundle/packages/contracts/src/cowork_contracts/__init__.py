def __getattr__(name: str):
    if name in _TELEMETRY_EXPORTS:
        from . import telemetry

        value = getattr(telemetry, name)
        globals()[name] = value
        return value
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")

